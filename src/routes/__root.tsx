function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  useEffect(() => {
    if (typeof window === "undefined") return;
    const path = window.location.pathname;
    if (path.startsWith("/admin")) return;
    let sid = window.sessionStorage.getItem("mutken-session-id");
    if (!sid) {
      sid = `shop-${Math.random().toString(36).slice(2, 10)}`;
      window.sessionStorage.setItem("mutken-session-id", sid);
    }
    const ping = () => {
      let basketCount = 0;
      try {
        const raw = window.localStorage.getItem("mutken-basket");
        if (raw) {
          const parsed = JSON.parse(raw);
          if (Array.isArray(parsed)) basketCount = parsed.length;
        }
      } catch {
        basketCount = 0;
      }
      fetch("/api/public/sessions", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ id: sid, role: "shopper", path: window.location.pathname, basketCount }),
      }).catch(() => {});
    };
    ping();
    const timer = window.setInterval(ping, 25_000);
    return () => window.clearInterval(timer);
  }, []);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <BasketProvider>
        <Outlet />
      </BasketProvider>
      <Toaster position="top-center" richColors />
    </QueryClientProvider>
  );
}
